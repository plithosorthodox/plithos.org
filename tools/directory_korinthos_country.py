def build():
    ids = set()
    ranks = Counter()
    kinds = Counter()
    result = []
    for source in ROWS:
        item = {
            key: value for key, value in source.items()
            if value not in (None, "", [])
        }
        row_id = item.get("id")
        if not row_id or row_id in ids:
            raise ValueError("duplicate or missing id: %s" % row_id)
        if item.get("parent") != PARENT or item.get("country") != "GR":
            raise ValueError("%s has the wrong parent or country" % row_id)
        if not item.get("name") or not item.get("local") or not item.get("seat"):
            raise ValueError("%s lacks name or seat data" % row_id)
        if not any("\u0370" <= char <= "\u03ff" for char in item["local"]):
            raise ValueError("%s lacks a Greek source name" % row_id)
        if any(FORBIDDEN_PUNCTUATION.search(value)
               for value in walk_strings(item)):
            raise ValueError("%s contains forbidden punctuation" % row_id)
        address = item.get("address") or []
        if len(address) != 2 or not all(address):
            raise ValueError("%s lacks its current public address" % row_id)
        sources = list(item.get("sources") or [])
        if not sources or len(sources) > 2:
            raise ValueError("%s lacks valid sources" % row_id)
        for source_url in sources:
            validate_url(source_url, row_id)
        item["sources"] = sources
        item["cite"] = list(sources)
        contact_sources = list(item.get("contact_sources") or [])
        has_contact = bool(
            item.get("phones") or item.get("faxes") or
            item.get("emails") or item.get("site")
        )
        if has_contact:
            if not contact_sources or item.get("contact_checked") != CHECKED:
                raise ValueError("%s lacks current contact provenance" % row_id)
            for phone in item.get("phones") or []:
                if not re.fullmatch(r"[26]\d{9}", phone):
                    raise ValueError("%s carries an invalid phone" % row_id)
            for fax in item.get("faxes") or []:
                if not re.fullmatch(r"2\d{9}", fax):
                    raise ValueError("%s carries an invalid fax" % row_id)
            for source_url in contact_sources:
                validate_url(source_url, row_id)
                if source_url not in sources:
                    raise ValueError("contact source is outside identity sources")
        elif contact_sources or "contact_checked" in item:
            raise ValueError(
                "%s carries contact provenance without contact data" % row_id
            )
        ids.add(row_id)
        ranks[item["rank"]] += 1
        kinds[item["kind"]] += 1
        result.append(item)
    if len(result) != EXPECTED_TOTAL:
        raise ValueError("expected %d bodies, found %d" %
                         (EXPECTED_TOTAL, len(result)))
    if set(ENGLISH_NAMES) != ids or len(ENGLISH_SEATS) < 100:
        raise ValueError("Korinthos English coverage drifted")
    if dict(sorted(ranks.items())) != EXPECTED_RANKS:
        raise ValueError("Korinthos rank totals drifted: %r" % dict(ranks))
    if dict(sorted(kinds.items())) != EXPECTED_KINDS:
        raise ValueError("Korinthos kind totals drifted: %r" % dict(kinds))
    phone_bodies = sum(bool(item.get("phones")) for item in result)
    phone_values = sum(len(item.get("phones") or []) for item in result)
    contact_bodies = sum(bool(
        item.get("phones") or item.get("faxes") or
        item.get("emails") or item.get("site")
    ) for item in result)
    if (phone_bodies, phone_values, contact_bodies) != (
            EXPECTED_PHONE_BODIES, EXPECTED_PHONE_VALUES,
            EXPECTED_PHONE_BODIES):
        raise ValueError("Korinthos contact coverage drifted")
    if any(
            item.get("faxes") or item.get("emails") or item.get("site")
            for item in result):
        raise ValueError("Korinthos fax, email, or site coverage drifted")
    validate_ledger()
    return {PARENT: {
        "v": 1,
        "parent": PARENT,
        "country": "GR",
        "rows": result,
    }}


def fetch(url):
    headers = {
        "User-Agent": "Mozilla/5.0 Plithos directory source audit",
        "Accept": "application/json,text/html,application/xhtml+xml,application/pdf",
        "Accept-Encoding": "identity",
    }
    if url == LEGAL_PDF:
        headers["Range"] = "bytes=0-4095"
    last_error = None
    for attempt in range(3):
        try:
            request = Request(url, headers=headers)
            with urlopen(request, timeout=30) as response:
                payload = response.read()
                content_type = response.headers.get("Content-Type", "").lower()
            return payload, content_type
        except (HTTPError, URLError, TimeoutError) as exc:
            last_error = exc
            if attempt < 2:
                time.sleep(2)
    raise last_error


def normalized_page(payload):
    text = payload.decode("utf-8", "replace")
    text = html.unescape(re.sub(r"<[^>]+>", " ", text))
    text = text.replace("\u2013", "-").replace("\u2014", "-")
    return unicase(" ".join(text.split()))


def canonical_url(value):
    parsed = urlparse(value)
    path = parsed.path.rstrip("/") + "/"
    return "%s://%s%s" % (parsed.scheme, parsed.netloc.lower(), path)


def check_live():
    def one_page(item):
        page_id, url = item
        payload, content_type = fetch(url)
        if "html" not in content_type:
            raise ValueError("non-HTML Korinthos source: %s" % url)
        page = normalized_page(payload)
        marker = unicase(PAGE_MARKERS[page_id])
        if marker not in page:
            raise ValueError("%s lacks its roster marker" % url)
        return url

    with ThreadPoolExecutor(max_workers=8) as executor:
        list(executor.map(one_page, PAGE_URLS.items()))

    payload, content_type = fetch(WP_API)
    if "json" not in content_type:
        raise ValueError("non-JSON Korinthos WordPress roster")
    records = json.loads(payload.decode("utf-8"))
    ids = {record.get("id") for record in records}
    if ids != set(PAGE_URLS):
        raise ValueError(
            "Korinthos WordPress page inventory drifted: expected %d, found %d" %
            (len(PAGE_URLS), len(ids))
        )
    for record in records:
        page_id = record["id"]
        if canonical_url(record.get("link", "")) != canonical_url(PAGE_URLS[page_id]):
            raise ValueError("Korinthos WordPress page link drifted: %s" % page_id)
    parish_items = []
    for record in records:
        page_id = record["id"]
        if page_id not in PARISH_PAGE_COUNTS:
            continue
        content = (record.get("content") or {}).get("rendered", "")
        items = []
        for fragment in re.findall(
                r"<li\b[^>]*>(.*?)</li>", content,
                flags=re.IGNORECASE | re.DOTALL):
            value = html.unescape(re.sub(r"<[^>]+>", " ", fragment))
            items.append(unicase(" ".join(value.split())))
        if len(items) != PARISH_PAGE_COUNTS[page_id]:
            raise ValueError(
                "Korinthos parish heading count drifted at page %s: %d" %
                (page_id, len(items))
            )
        parish_items.extend(items)
    counts = Counter(parish_items)
    duplicates = [value for value, count in counts.items() if count > 1]
    if len(parish_items) != 165 or len(counts) != 164 or len(duplicates) != 1:
        raise ValueError(
            "Korinthos current parish deduplication drifted: %d raw, %d unique" %
            (len(parish_items), len(counts))
        )
    if "ελληνοχωριου" not in duplicates[0]:
        raise ValueError("Korinthos current duplicate identity drifted")
    current_content = " ".join(
        (record.get("content") or {}).get("rendered", "")
        for record in records
    )
    if re.search(r"mailto:|[\w.+-]+@[\w.-]+[.]\w+", current_content,
                 flags=re.IGNORECASE):
        raise ValueError("Korinthos current pages expose a new body email lead")
    if re.search(r"\bFAX\b|ΦΑΞ", current_content, flags=re.IGNORECASE):
        raise ValueError("Korinthos current pages expose a new body fax lead")
    external_links = []
    for value in re.findall(
            r'''href=["']([^"']+)["']''', current_content,
            flags=re.IGNORECASE):
        parsed = urlparse(html.unescape(value))
        if parsed.scheme in {"http", "https"} and parsed.netloc.lower() not in {
                "imkorinthou.org", "www.imkorinthou.org"}:
            external_links.append(value)
    if external_links:
        raise ValueError("Korinthos current pages expose a new direct site lead")

    payload, content_type = fetch(LEGAL_PDF)
    if "pdf" not in content_type and not payload.startswith(b"%PDF"):
        raise ValueError("Korinthos regulation is not a PDF")
    return len(PAGE_URLS) + 2


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--check-live", action="store_true")
    parser.add_argument("--dump", action="store_true")
    args = parser.parse_args()
    try:
        data = build()
        if args.check_live:
            checked = check_live()
            print(
                "Korinthos live checks passed for %d source surfaces" % checked
            )
        if args.dump:
            print(json.dumps(data, ensure_ascii=False, indent=2))
        elif args.check or not args.check_live:
            rows = data[PARENT]["rows"]
            print(
                "Korinthos checks passed: %d bodies, %d contact bodies, "
                "%d public phone values, 0 body sites" % (
                    len(rows),
                    sum(bool(item.get("phones")) for item in rows),
                    sum(len(item.get("phones") or []) for item in rows),
                )
            )
    except Exception as exc:
        print("Korinthos check failed: %s" % exc, file=sys.stderr)
        return 1
    return 0


