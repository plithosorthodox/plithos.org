def unicase(value):
    value = unicodedata.normalize("NFD", value).casefold()
    return "".join(
        char for char in value if unicodedata.category(char) != "Mn"
    )


def transliterate(value):
    value = "".join(
        char for char in unicodedata.normalize("NFD", value.upper())
        if unicodedata.category(char) != "Mn"
    )
    digraphs = {
        "ΟΥ": "ou", "ΑΙ": "ai", "ΕΙ": "ei", "ΟΙ": "oi",
        "ΑΥ": "av", "ΕΥ": "ev", "ΓΓ": "ng", "ΓΚ": "g",
        "ΜΠ": "mp", "ΝΤ": "nt",
    }
    for greek, latin in digraphs.items():
        value = value.replace(greek, latin)
    letters = {
        "Α": "a", "Β": "v", "Γ": "g", "Δ": "d", "Ε": "e",
        "Ζ": "z", "Η": "i", "Θ": "th", "Ι": "i", "Κ": "k",
        "Λ": "l", "Μ": "m", "Ν": "n", "Ξ": "x", "Ο": "o",
        "Π": "p", "Ρ": "r", "Σ": "s", "Τ": "t", "Υ": "y",
        "Φ": "f", "Χ": "ch", "Ψ": "ps", "Ω": "o", "ς": "s",
    }
    value = "".join(letters.get(char, char) for char in value)
    value = re.sub(r"\s+", " ", value).strip()
    return value.title()


def walk_strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from walk_strings(item)
    elif isinstance(value, list):
        for item in value:
            yield from walk_strings(item)


