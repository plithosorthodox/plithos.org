"""The forty-four eparchies of the Orthodox Church of Ukraine.

Read on 14 September 2026 from the Church's own map of its eparchies at
https://www.pomisna.info/uk/tserkva/karta-yeparhij/, which is the only list
of its eparchies the Church publishes, and then from each eparchy's own site
where it has one and the site answered. The map holds 31 eparchies. 36 rows
were written from it, and the difference is set out below.

Eight more were added the same day, and they came from somewhere else,
because the map is not what the Church says about itself. The Church states
a number, and it states it in its own Primate's report to the Bishops'
Council of 14 July 2026: "Православна Церква України на даний час
складається з 46 єпархій". Forty-six. The report before it, of 14 December
2019, said
forty-four. The map says thirty-one, and its address block still carries a
Kyiv monastery under every eparchy and its Kyiv entry still names a Patriarch
who reposed in March 2026; it was built once and left. A count taken from it
is a count of a page nobody has touched in seven years.

So the eight were read from the Church's own Synod, whose documents name an
eparchy by name where the map does not: the journals and Postanovy published
under Документи. Five of them are eparchies the map never carried at all -
Lviv and Sokal, Ivano-Frankivsk and Halych, Uzhhorod and Khust, Chernivtsi
and Khotyn, Rivne and Volyn - each named in a Synod document beside the
eparchy of the same city the directory already held, which is how their
separateness is known rather than guessed. Kyiv, Lviv, Ivano-Frankivsk,
Rivne, Kharkiv, Kherson, Donetsk, Chernivtsi and Transcarpathia each hold
more than one eparchy, and that is what the union of December 2018 left
behind, not an error in the reading.

The other three were created after the map was made and the Synod's decree
creating each is quoted on its row: Bila Tserkva by Postanova No. 38 of 2
February 2023, Vyshhorod by No. 75 and Kamianets-Podilskyi by No. 80, both of
2 February 2024.

That leaves forty-four rows against the forty-six the Church names, and the
two that are short are named here so the next reading knows where to look
rather than starting again. The Synod's own words carry a Таврійська єпархія
(2 February 2026) and a Богородська єпархія (4 March 2019), and neither is
written. Tavria may be the Kherson eparchy under a newer name - the bishop
the Synod appointed to Kherson in August 2020 bears the title Херсонський і
Таврійський - and a row that turned out to be a second copy of `ocu-kherson`
would be worse than a gap. Bohorodsk is named in 2019 and in nothing since;
the metropolitan who bears the title still stands on the Church's page of its
bishops, which is suggestive and is not a list. Two further names from that
same 2019 journal, Білгородська and Білгород-Дністровська, were looked into
and left: the first belonged to a bishop who has since set himself up against
the Church from Russia, which the Primate's 2026 report says in as many
words. A missing eparchy is better than a wrong one, and that rule has now
been applied four times in this file.

The map names the eparchies region by region and prints nothing else that can
be used: the address block under every one of them carries the same Kyiv
monastery, which is the template the page was built on and was never filled
in. So the names are the map's and the addresses are each eparchy's own,
taken from its own site, and a row carries an address only where its own site
prints one.

Three decisions were taken and are written here so they are not taken again:

  - Two of the map's names are the Church's older regional ones, and the
    eparchies themselves publish under longer ones. Zhytomyr is one eparchy
    on the map and two that publish - Zhytomyr and Ovruch, Zhytomyr and
    Polissia - and Pereiaslav publishes as Pereiaslav and Vyshneve. Those
    rows are written as the eparchies write themselves, and the map's shorter
    name is not written a second time beside them.
  - Five eparchies publish sites of their own that the map does not name at
    all - Vinnytsia and Bar, Vinnytsia and Tulchyn, Mukachevo and the
    Carpathians, Ternopil and Buchach, Kharkiv and Poltava - and each has a
    row on its own site's authority, which is the rule the whole directory
    runs on: a row names its source when the source belongs to it. That
    several places hold more than one eparchy apiece - Vinnytsia, Ternopil,
    Kharkiv, Zhytomyr, Transcarpathia - is not an error in the reading. The
    Church's own page of its bishops names a ruling bishop for each of them
    separately, and each publishes its own site. No row here says which of
    two eparchies in one city is the elder, or whether either stands over the
    other; the directory records what each published page says of itself.
  - The map carries a thirty-first name, in Chernivtsi region, that no page
    of the Church's own and no eparchy site could be found to confirm, and it
    is the one row not written. A missing eparchy is better than a wrong one.

A seat is written only where the eparchy's own site prints an address that
names the town, so nothing on a row is inferred from the name of a region.
Twenty-seven rows accordingly carry no address, and twenty-four of those
carry no link of their own either: a name, a country and a citation, which is
the directory's declared minimum. A reader who learns that an eparchy exists,
and where to read about it, has been given something, and an eparchy left out
because its address could not be found has been hidden from him.

The nineteen that wanted addresses still want them, and this reading did not
supply one. Nothing on pomisna.info carries an eparchy's address: the map's
block is the unfilled template, and every page of the Church's own - the
bishops, the Synod's documents, the Primate's reports - prints the Kyiv
Metropolia's address at Трьохсвятительська 8 and no other. The addresses that
are here were each taken from the eparchy's own site, and the eight added
from the Synod have no site of their own to take one from.

Two of the sites still carry the name of the Church their eparchy belonged to
before December 2018 - Crimea and Drohobych and Sambir both style themselves
of the Kyiv Patriarchate. The address each prints is the address each prints,
and the row carries it; the row's name is the one the Orthodox Church of
Ukraine gives the eparchy on its own map.

Volyn and Transcarpathia have sites of their own that refused the request
from here rather than failing to answer, and half a dozen more addresses that
were tried did not resolve at all. Those rows carry no link and fall back to
the Church's own map, which does answer. They are to be tried again, not
written off.

Addresses are each site's own words, set out as an envelope wants them: the
street on one line, the postcode and town on the next. Nothing is translated
and nothing is added. The country line is dropped, because the page writes it
in the reader's language.

Twenty-five rows stood on a single page and twenty-four of them now stand on
two. The second is the Church's own in every case: sixteen are a Synod
document, which names an eparchy in the act it is performing upon it, and
eight are the Church's own news, which names an eparchy in reporting where
the Primate served or what an eparchy lost. Each was fetched and the
eparchy's name read in it; a document that merely ranked high in a search of
the site was not taken on the ranking. Two rows that already had two gained
a third, Ternopil and Terebovlia and Chernihiv, because each publishes a
history page that states its own beginning.

Kirovohrad is the one left standing on the map alone, and the reason is worth
writing down rather than fixing. Nothing the Church has published since names
a Кіровоградська єпархія. Its Synod's documents and its news both say
Кропивницька, and its bishop signs as Кропивницький і Голованівський - the
regional city was renamed in 2016 and the eparchy followed. Citing a page
that says Кропивницька under a row that says Кіровоградська would be a second
source got by assuming the two are one, which they almost certainly are and
which no page here says. So the row keeps its one honest source and the name
the map still prints, and the next reading has the question in front of it.

Chernivtsi carries the same shape of doubt and was left alone for the same
reason. The Synod's postanova of 2 February 2026 speaks of a
Чернівецько-Буковинська єпархія where the map says Чернівецька, and the
directory already holds a separate Чернівецько-Хотинська. Three names over
two rows is not something to resolve from one sentence.

uaoch.com answers again. The Kharkiv and Poltava eparchy's site was
unreachable at the last reading and now serves its own title over https, with
the postal address the row already carries. Its link stays and its row is
stamped today.

No address that was missing has appeared. The nineteen rows that wanted one
still want it: pomisna.info publishes none, and the eparchy sites that were
tried again either print no address or answer with an empty contacts page.

`rank` is written on all forty-four, and it is each Church page's own word:
the map heads every entry єпархія and so does every Synod document that
names one, so every row says Eparchy.

`founded` is on five. The three that were already here quote the Synod's
postanova; Ternopil and Terebovlia and Chernihiv quote what their own sites
publish about their own beginnings. No other eparchy's beginning is stated
anywhere the Church publishes: the Synod's documents reach back to 2019 and
the rest were formed at the union or before it.

`languages` is on none of them. The phrase "українською мовою" is all over
the Synod's documents and every occurrence of it is the legal name of a
religious organisation, not a statement about worship.
"""

